// Generate a standalone declaration for page authors from the actual Backend and Rust DTOs.
import ts from "typescript";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const visited = new Set();
const declarations = [];
const symbols = new Set();
async function collect(relative) {
  const filename = path.resolve(root, relative);
  if (visited.has(filename)) return;
  visited.add(filename);
  const source = await readFile(filename, "utf8");
  const ast = ts.createSourceFile(filename, source, ts.ScriptTarget.Latest, true);
  const nodes = ast.statements.filter(
    (n) => ts.isInterfaceDeclaration(n) || ts.isTypeAliasDeclaration(n),
  );
  let text = nodes.map((n) => n.getText(ast)).join("\n\n");
  const dependencies = [];
  for (const node of ast.statements) {
    if (
      !ts.isImportDeclaration(node) ||
      !node.importClause?.namedBindings ||
      !ts.isNamedImports(node.importClause.namedBindings)
    )
      continue;
    if (
      node.importClause.namedBindings.elements.some((e) =>
        new RegExp(`\\b${e.name.text}\\b`).test(text),
      )
    ) {
      dependencies.push(path.resolve(path.dirname(filename), node.moduleSpecifier.text) + ".ts");
    }
  }
  text = text.replace(/import\("(.+?)"\)\.(\w+)/g, (_, module, name) => {
    dependencies.push(path.resolve(path.dirname(filename), module) + ".ts");
    return name;
  });
  if (relative.endsWith("/backend.ts"))
    text = text.replace("export interface Backend", "interface ApplicationBackend");
  for (const dependency of dependencies) await collect(path.relative(root, dependency));
  for (const match of text.matchAll(/(?:interface|type)\s+(\w+)/g)) {
    if (symbols.has(match[1])) throw new Error(`duplicate declaration ${match[1]}`);
    symbols.add(match[1]);
  }
  declarations.push(text);
}
await collect("src/api/session-page-backend.ts");
const output =
  "// Generated by scripts/export-session-page-types.mjs. Do not edit.\n\n" +
  declarations.join("\n\n") +
  "\n";
const destination = path.join(root, "skills/proxycrab/references/session-page-backend.d.ts");
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== output)
    throw new Error("Session page types are stale; run node scripts/export-session-page-types.mjs");
} else await writeFile(destination, output);
